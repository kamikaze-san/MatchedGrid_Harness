# ---------------------------------------------------------------- gamma heatmaps
def gamma_sig(j):
    k, n, A = matrix(j)
    mu, alpha, beta, g = decompose(A)
    rng = np.random.default_rng(0)  # same seed as appendix_latex.gamma()
    boot = np.array([decompose(100 * rng.binomial(n.astype(int), k / n) / n)[3] for _ in range(2000)])
    lo, hi = np.percentile(boot, [2.5, 97.5], axis=0)
    return g, (lo > 0) | (hi < 0)


def cell(v, s, gmax, x, y, w, h, font):
    """One heatmap cell: diverging fill (teal +, brown -), value, * if the interval excludes zero."""
    p = int(round(85 * min(1, abs(v) / gmax)))
    col = ("posc" if v > 0 else "negc") + f"!{p}!white"
    ink = "white" if p > 55 else "black"
    txt = f"{v:+.1f}".replace("-", "$-$") + ("$^{*}$" if s else "")
    return (rf"\fill[{col}] ({x:.2f},{y:.2f}) rectangle ++({w - 0.03:.2f},{h - 0.03:.2f});" + "\n"
            + rf"\node[font={font}, text={ink}] at ({x + w / 2 - 0.015:.3f},{y + h / 2 - 0.015:.3f}) {{{txt}}};")


def heat_panel(j, x0, labels, cw=0.95, ch=0.42, title=None,
               vfont=r"\tiny", hfont=r"\tiny", lfont=r"\scriptsize", tfont=r"\scriptsize\bfseries"):
    """Targets as rows, attacks as columns."""
    g, sig = gamma_sig(j)
    gmax = np.abs(g).max()
    out = []
    if title:
        out.append(rf"\node[font={tfont}, anchor=south] at ({x0 + cw * 2.5:.2f},{ch * 8 + 0.45:.2f}) {{{title}}};")
    for i, m in enumerate(METHODS):
        out.append(rf"\node[font={hfont}, anchor=south, inner sep=1pt] at ({x0 + cw * (i + 0.5):.2f},{ch * 8 + 0.03:.2f}) "
                   rf"{{{TSHORT[m]}}};")
    for c, (t, _) in enumerate(TARGETS):
        y = ch * (7 - c)
        if labels:
            out.append(rf"\node[font={lfont}, anchor=east] at ({x0 - 0.06:.2f},{y + ch / 2:.2f}) {{{SHORT[t]}}};")
        for i in range(len(METHODS)):
            out.append(cell(g[i, c], sig[i, c], gmax, x0 + cw * i, y, cw, ch, vfont))
    return "\n".join(out)


def heat_wide(j, cw=1.62, ch=0.56):
    """Attacks as rows, targets as columns (for a full-width single-judge figure)."""
    g, sig = gamma_sig(j)
    gmax = np.abs(g).max()
    M = len(METHODS)
    out = []
    two = {"internvl25_8b": r"InternVL2.5\\8B", "internvl25_26b": r"InternVL2.5\\26B", "qwen25vl7b": r"Qwen2.5-VL\\7B",
           "qwen25vl_32b": r"Qwen2.5-VL\\32B", "llava_ov_7b": r"LLaVA-OV\\7B", "phi35_vision": r"Phi-3.5\\Vision",
           "minicpm_v26": r"MiniCPM-V\\2.6", "pixtral_12b": r"Pixtral\\12B"}
    for c, (t, _) in enumerate(TARGETS):
        out.append(rf"\node[font=\scriptsize, anchor=south, inner sep=1pt, align=center] at "
                   rf"({cw * (c + 0.5):.2f},{ch * M + 0.03:.2f}) {{{two[t]}}};")
    for i, m in enumerate(METHODS):
        y = ch * (M - 1 - i)
        out.append(rf"\node[font=\footnotesize, anchor=east] at (-0.06,{y + ch / 2:.2f}) {{{MSHORT[m]}}};")
        for c in range(len(TARGETS)):
            out.append(cell(g[i, c], sig[i, c], gmax, cw * c, y, cw, ch, r"\footnotesize"))
    return "\n".join(out)


