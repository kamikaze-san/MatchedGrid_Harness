def waterfall():
    _, _, A = matrix("qwen7b")
    mu, alpha, beta, g = decompose(A)
    i = METHODS.index("figstep")
    tgt = [("internvl25_8b", "InternVL2.5-8B"), ("qwen25vl7b", "Qwen2.5-VL-7B")]
    ys, bw, gap = 0.2, 0.42, 0.14   # cm per pp, bar width, gap
    out = [r"\begin{tikzpicture}[font=\scriptsize]"]
    top = 14
    for p, (t, name) in enumerate(tgt):
        c = [k for k, _ in TARGETS].index(t)
        comps = [(r"$\mu$", mu, "black!35"), (r"$\alpha$", alpha[i], "mFig!55"), (r"$\beta$", beta[c], "black!20"),
                 (r"$\gamma$", g[i, c], "posc" if g[i, c] > 0 else "negc")]
        x0 = p * (5 * (bw + gap) + 0.7)
        run = 0.0
        for q, (lab, v, col) in enumerate(comps):
            x = x0 + q * (bw + gap)
            lo, hi = sorted((run, run + v))
            out.append(rf"\fill[{col}] ({x:.2f},{lo * ys:.3f}) rectangle ++({bw:.2f},{(hi - lo) * ys:.3f});")
            if q:
                out.append(rf"\draw[black!40, densely dotted] ({x - gap:.2f},{run * ys:.3f}) -- ({x:.2f},{run * ys:.3f});")
            vs = f"{v:+.1f}".replace("-", "$-$")
            out.append(rf"\node[anchor=south, inner sep=1pt] at ({x + bw / 2:.2f},{hi * ys:.3f}) {{{vs}}};"
                       if q else rf"\node[anchor=south, inner sep=1pt] at ({x + bw / 2:.2f},{hi * ys:.3f}) {{{v:.1f}}};")
            out.append(rf"\node[anchor=north, inner sep=2pt] at ({x + bw / 2:.2f},0) {{{lab}}};")
            run += v
        x = x0 + 4 * (bw + gap)
        out.append(rf"\draw[black!40, densely dotted] ({x - gap:.2f},{run * ys:.3f}) -- ({x:.2f},{run * ys:.3f});")
        out.append(rf"\fill[mFig] ({x:.2f},0) rectangle ++({bw:.2f},{run * ys:.3f});")
        out.append(rf"\node[anchor=south, inner sep=1pt, font=\scriptsize\bfseries] at ({x + bw / 2:.2f},{run * ys:.3f}) {{{run:.1f}}};")
        out.append(rf"\node[anchor=north, inner sep=2pt] at ({x + bw / 2:.2f},0) {{ASR}};")
        out.append(rf"\draw[black!60] ({x0 - 0.08:.2f},0) -- ({x + bw + 0.08:.2f},0);")
        out.append(rf"\node[anchor=north, font=\scriptsize\bfseries] at ({x0 + 2.5 * (bw + gap) - gap / 2:.2f},-0.38) {{{name}}};")
    out.append(r"\end{tikzpicture}")
    write("f_waterfall", "\n".join([
        r"\begin{figure}[t]", r"\centering", COLDEFS, *out,
        rf"\caption{{FigStep's ASR (\%, primary judge) on two targets, built up from the grand mean $\mu$, its general "
        rf"strength $\alpha$, the target's susceptibility $\beta$ and its target-specific fit $\gamma$. The general "
        rf"strength is the same on both targets; the tenfold difference comes from $\beta$ and, mostly, $\gamma$.}}",
        r"\label{fig:waterfall}", r"\end{figure}", ""]))


# ---------------------------------------------------------------- judge shift
def judge_shift():
    _, _, A7 = matrix("qwen7b")
    _, _, A72 = matrix("qwen72b")
    m7, m72 = A7.mean(1), A72.mean(1)
    L = lambda v: 5.2 * (np.log10(v) - np.log10(0.8)) / (np.log10(50) - np.log10(0.8))   # cm
    order = np.argsort(-m72)
    out = [r"\begin{tikzpicture}[font=\scriptsize]"]
    H = 0.42
    for v in (1, 2, 5, 10, 20, 50):
        out.append(rf"\draw[gridc] ({L(v):.2f},-0.15) -- ({L(v):.2f},{H * len(order):.2f});")
        out.append(rf"\node[anchor=north, text=inkc] at ({L(v):.2f},-0.15) {{{v}}};")
    out.append(rf"\node[anchor=north] at ({L(6.3):.2f},-0.5) {{mean ASR over the eight targets (\%, log scale)}};")
    for r, i in enumerate(order):
        y = H * (len(order) - r - 0.5)
        m = METHODS[i]
        out.append(rf"\node[anchor=east] at (-0.1,{y:.2f}) {{{MSHORT[m]}}};")
        out.append(rf"\draw[black!35, line width=1.2pt] ({L(m7[i]):.2f},{y:.2f}) -- ({L(m72[i]):.2f},{y:.2f});")
        out.append(rf"\fill[serA] ({L(m7[i]):.2f},{y:.2f}) circle (2.2pt);")
        out.append(rf"\fill[serB] ({L(m72[i]):.2f},{y:.2f}) circle (2.2pt);")
        out.append(rf"\node[anchor=west, text=inkc] at ({L(m72[i]) + 0.1:.2f},{y:.2f}) {{${m72[i] / m7[i]:.1f}\times$}};")
    ly = H * len(order) + 0.25
    out.append(rf"\fill[serA] (0.1,{ly:.2f}) circle (2.2pt); \node[anchor=west] at (0.2,{ly:.2f}) {{Qwen2.5-7B judge}};")
    out.append(rf"\fill[serB] (2.6,{ly:.2f}) circle (2.2pt); \node[anchor=west] at (2.7,{ly:.2f}) {{Qwen2.5-72B judge}};")
    out.append(r"\end{tikzpicture}")
    write("f_judge_shift", "\n".join([
        r"\begin{figure}[t]", r"\centering", COLDEFS, *out,
        r"\caption{Mean ASR of each attack under the two Qwen judges, which share the same prompt and threshold. "
        r"The larger judge raises every attack, but by different factors, which changes the per-target ranking "
        r"(Section~\ref{sec:sensitivity}).}",
        r"\label{fig:judge_shift}", r"\end{figure}", ""]))


